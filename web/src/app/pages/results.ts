import { Component, computed, inject, signal } from '@angular/core';
import { toObservable, toSignal } from '@angular/core/rxjs-interop';
import { ActivatedRoute, Router } from '@angular/router';
import { marked } from 'marked';
import { filter, map, switchMap } from 'rxjs';
import { ApiService } from '../core/api.service';
import { ResultSection } from '../core/models';

@Component({
  selector: 'app-results',
  template: `
  <section class="page">
    <header class="page-head">
      <h1>Results &amp; figures</h1>
      <p>Every headline estimate from <code>results/RESULTS.md</code>, regenerated by
         <code>python reproduce.py</code>, plus the thesis figures.</p>
    </header>
    <div class="tabs" role="tablist">
      <button role="tab" class="chip" [class.on]="tab() === 'results'" (click)="tab.set('results')">Results</button>
      <button role="tab" class="chip" [class.on]="tab() === 'figures'" (click)="tab.set('figures')">Figures</button>
    </div>

    @if (tab() === 'results') {
      <div class="layout">
        <nav class="card toc">
          @for (g of grouped(); track g.track) {
            <h3>{{ g.track }}</h3>
            @for (s of g.items; track s.id) {
              <button type="button" [class.on]="s.id === id()" (click)="select(s.id)">
                <b>{{ s.id }}</b> {{ s.title }}</button>
            }
          }
        </nav>
        <article class="card md">
          @if (html()) { <div [innerHTML]="html()"></div> } @else { <span class="spinner"></span> }
        </article>
      </div>
    } @else {
      <div class="figs">
        @for (f of figures() ?? []; track f.name) {
          <figure class="card">
            <a [href]="f.png" target="_blank" rel="noopener"><img [src]="f.png" [alt]="f.title" loading="lazy"></a>
            <figcaption><span>{{ f.title }}</span>
              <span class="links"><a [href]="f.png" target="_blank" rel="noopener">PNG</a> ·
                <a [href]="f.pdf" target="_blank" rel="noopener">PDF</a></span></figcaption>
          </figure>
        }
      </div>
    }
  </section>`,
  styles: [`
    .tabs { display: flex; gap: 6px; }
    .layout { display: grid; grid-template-columns: 300px minmax(0, 1fr); gap: 16px; align-items: start; }
    @media (max-width: 1000px) { .layout { grid-template-columns: 1fr; } .toc { max-height: 280px; } }
    .toc { position: sticky; top: 16px; max-height: calc(100vh - 32px); overflow: auto; display: grid; gap: 2px; align-content: start; }
    .toc h3 { margin: 10px 6px 4px; font-size: 11px; text-transform: uppercase; letter-spacing: .04em; color: var(--muted); }
    .toc h3:first-child { margin-top: 0; }
    .toc button { all: unset; cursor: pointer; padding: 6px 8px; border-radius: 6px; font-size: 12.5px;
      color: var(--ink-2); line-height: 1.35; }
    .toc button:hover { background: var(--surface-2); }
    .toc button.on { background: var(--surface-2); color: var(--ink); }
    .toc button b { color: var(--accent); margin-right: 4px; }
    code { font-size: 12.5px; background: var(--surface-2); padding: 1px 5px; border-radius: 4px; }
    .figs { display: grid; gap: 16px; grid-template-columns: repeat(auto-fill, minmax(380px, 1fr)); }
    @media (max-width: 500px) { .figs { grid-template-columns: 1fr; } }
    figure { margin: 0; display: grid; gap: 10px; }
    figure img { width: 100%; height: auto; border-radius: 8px; background: #fff; display: block; }
    figcaption { display: flex; justify-content: space-between; gap: 8px; font-size: 13px; }
    .links { color: var(--muted); font-size: 12px; white-space: nowrap; }
  `],
})
export class Results {
  private api = inject(ApiService);
  private route = inject(ActivatedRoute);
  private router = inject(Router);
  protected tab = signal<'results' | 'figures'>('results');
  protected index = toSignal(this.api.results(), { initialValue: [] as ResultSection[] });
  protected figures = toSignal(this.api.figures());
  private qid = toSignal(this.route.queryParamMap.pipe(map(p => p.get('id'))));
  protected id = computed(() => this.qid() ?? this.index()[0]?.id ?? '');

  protected grouped = computed(() => {
    const out: { track: string; items: ResultSection[] }[] = [];
    const order = ['Thesis panel', 'Rebuilt panel', 'Convergence', 'Policy variables'];
    for (const tr of order) {
      const items = this.index().filter(s => s.track === tr)
        .sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));
      if (items.length) out.push({ track: tr, items });
    }
    return out;
  });

  protected html = toSignal(toObservable(this.id).pipe(
    filter(Boolean), switchMap(id => this.api.result(id)),
    map(r => marked.parse(r.markdown, { async: false }) as string)));

  protected select(id: string) {
    this.router.navigate([], { queryParams: { id }, replaceUrl: true });
  }
}
